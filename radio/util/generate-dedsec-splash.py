#!/usr/bin/env python3

"""Convert the final DedSec GIF into compact delta-compressed 1-bit frames."""

import argparse
from pathlib import Path

from PIL import Image, ImageSequence


WIDTH = 320
HEIGHT = 240
FRAME_BYTES = WIDTH * HEIGHT // 8
MERGE_GAP = 4


def pack_frame(frame):
    mono = frame.convert("1")
    if mono.size != (WIDTH, HEIGHT):
        raise ValueError(f"expected {WIDTH}x{HEIGHT}, got {mono.size}")

    pixels = mono.load()
    packed = bytearray(FRAME_BYTES)
    for y in range(HEIGHT):
        row = y * WIDTH
        for x in range(WIDTH):
            if pixels[x, y]:
                bit = row + x
                packed[bit >> 3] |= 0x80 >> (bit & 7)
    return packed


def encode_delta(previous, current):
    changed = [i for i, (a, b) in enumerate(zip(previous, current)) if a != b]
    output = bytearray()
    position = 0
    index = 0

    while index < len(changed):
        start = changed[index]
        end = start + 1
        index += 1
        while index < len(changed) and changed[index] - end <= MERGE_GAP:
            end = changed[index] + 1
            index += 1

        skip = start - position
        count = end - start
        output += skip.to_bytes(2, "little")
        output += count.to_bytes(2, "little")
        output += current[start:end]
        position = end

    output += b"\xff\xff"
    return output


def format_values(values, width=16, formatter=lambda value: f"0x{value:02x}"):
    lines = []
    for offset in range(0, len(values), width):
        chunk = values[offset:offset + width]
        lines.append("  " + ", ".join(formatter(value) for value in chunk) + ",")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    image = Image.open(args.input)
    frames = [pack_frame(frame.copy()) for frame in ImageSequence.Iterator(image)]
    if not frames:
        raise ValueError("GIF contains no frames")

    delays = []
    image.seek(0)
    for frame_index in range(image.n_frames):
        image.seek(frame_index)
        delays.append(image.info.get("duration", 100))
    if any(delay != 100 for delay in delays):
        raise ValueError(f"expected uniform 100 ms timing, got {sorted(set(delays))}")

    encoded = bytearray()
    offsets = []
    previous = bytearray(FRAME_BYTES)
    for frame in frames:
        offsets.append(len(encoded))
        encoded += encode_delta(previous, frame)
        previous = frame
    offsets.append(len(encoded))

    content = f"""// Generated by radio/util/generate-dedsec-splash.py. Do not edit.
static constexpr uint16_t DEDSEC_SPLASH_WIDTH = {WIDTH};
static constexpr uint16_t DEDSEC_SPLASH_HEIGHT = {HEIGHT};
static constexpr uint16_t DEDSEC_SPLASH_FRAME_COUNT = {len(frames)};
static constexpr uint16_t DEDSEC_SPLASH_FRAME_MS = 100;
static constexpr uint32_t DEDSEC_SPLASH_PACKED_BYTES = {FRAME_BYTES};

static const uint32_t dedsecSplashFrameOffsets[] __FLASH = {{
{format_values(offsets, width=8, formatter=lambda value: str(value))}
}};

static const uint8_t dedsecSplashFrameData[] __FLASH = {{
{format_values(encoded)}
}};
"""
    args.output.write_text(content, encoding="utf-8")
    print(f"{len(frames)} frames, {len(encoded)} encoded bytes")


if __name__ == "__main__":
    main()
